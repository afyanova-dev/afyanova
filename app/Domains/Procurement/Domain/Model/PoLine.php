<?php

declare(strict_types=1);

namespace App\Domains\Procurement\Domain\Model;

use App\Domains\Procurement\Database\Factories\PoLineFactory;
use App\Domains\Procurement\Domain\Money;
use App\Shared\Concurrency\HasVersionColumn;
use App\Shared\Tenancy\BelongsToTenant;
use Carbon\CarbonImmutable;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;

/**
 * One line on a purchase order (19-procurement-domain.md §51, §52; ADR-171 D-G).
 *
 * Plain Eloquent child — NOT an AggregateRoot. `unit_price` is `Money` (scale 2);
 * `line_total` = `ordered_qty * unit_price` is COMPUTED via {@see lineTotal()},
 * never stored (the Inv.1 `available_qty` lesson). `received_qty` is written
 * ONLY by Proc.1b's `OnStockReceived` listener (Inv 15) — stays 0 in Proc.1a.
 * `version` is shape / conformance-only — stays 0. `contract_line_id` (Proc.3b,
 * ADR-177) links a contract-sourced line to its `pcr_contract_lines` row — the
 * state `committed` / `remaining` and the cumulative ceiling (INV-33a) derive
 * from; NULL on every non-contract line.
 *
 * PACK (buying unit, from `inventory-item-master-spec.md` §7): `ordered_qty` is
 * what the buyer TYPED and `unit_price` is the price of one `unit` (e.g. 3 BOX
 * at 10,000 per box). `uom` stays the item's BASE unit and `ordered_base_qty`
 * is generated by the database as `ordered_qty * coalesce(pack_size, 1)` — the
 * base truth that receiving, rollups and contract ceilings use. A line written
 * in the base unit has `unit = uom` and `pack_size = NULL`.
 *
 * @property string $id
 * @property string $tenant_id
 * @property string $facility_id
 * @property string $po_id
 * @property int $line_no
 * @property string $line_type
 * @property string|null $item_ref
 * @property string|null $contract_line_id
 * @property string|null $item_code
 * @property string|null $item_name
 * @property string|null $description
 * @property string $ordered_qty the quantity the buyer entered (in `$unit`)
 * @property string $uom the item's BASE unit (stock/receipts are in this)
 * @property string $unit the unit the buyer entered (e.g. BOX)
 * @property string|null $pack_size base units per `$unit` on this line; null when `$unit` IS the base unit
 * @property string $ordered_base_qty generated: ordered_qty * coalesce(pack_size, 1)
 * @property string $unit_price price of ONE `$unit`
 * @property string|null $delivery_location_ref
 * @property CarbonImmutable|null $required_date
 * @property string $received_qty
 * @property string $status
 * @property int $version
 */
class PoLine extends Model
{
    use BelongsToTenant;

    /** @use HasFactory<PoLineFactory> */
    use HasFactory;

    use HasUuids;
    use HasVersionColumn;

    public const LINE_TYPE_STOCK = 'STOCK';

    public const LINE_TYPE_SERVICE = 'SERVICE';

    public const STATUS_OPEN = 'OPEN';

    public const STATUS_CANCELLED = 'CANCELLED';

    /** P1-10 — the outstanding balance was closed without a cancellation. */
    public const STATUS_CLOSED_SHORT = 'CLOSED_SHORT';

    protected $table = 'pcr_po_lines';

    /** @var list<string> */
    protected $fillable = [
        'id', 'tenant_id', 'facility_id',
        'po_id', 'line_no', 'line_type',
        'item_ref', 'contract_line_id', 'item_code', 'item_name', 'description',
        'ordered_qty', 'uom', 'unit', 'pack_size', 'unit_price', 'delivery_location_ref', 'required_date',
        'received_qty', 'status', 'version',
    ];

    protected static function newFactory(): PoLineFactory
    {
        return PoLineFactory::new();
    }

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'line_no' => 'integer',
            'ordered_qty' => 'decimal:4',
            'pack_size' => 'decimal:4',
            'ordered_base_qty' => 'decimal:4',
            'unit_price' => 'decimal:2',
            'received_qty' => 'decimal:4',
            'required_date' => 'immutable_date',
            'version' => 'integer',
        ];
    }

    /**
     * ordered_qty × unit_price, at money scale — computed, never stored (F13).
     * Both sides are in the ENTERED unit, so a pack line never needs a divided
     * or rounded price: 3 BOX × 10,000/BOX = 30,000.
     */
    public function lineTotal(): string
    {
        return Money::multiplyByQuantity((string) $this->unit_price, (string) $this->ordered_qty);
    }

    /**
     * The ordered quantity in the item's BASE unit — the generated column, so a
     * pack line (3 BOX of 100) is 300 and a base line is unchanged.
     */
    public function baseQuantity(): string
    {
        return (string) $this->ordered_base_qty;
    }

    /** True when this line was ordered in a buying unit rather than the base unit. */
    public function isPacked(): bool
    {
        return $this->pack_size !== null;
    }
}
